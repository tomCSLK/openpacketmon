#!/usr/bin/env python3
"""Writes THIRD-PARTY-LICENSES.txt: the licenses of everything built into the release binaries.

Covers the Rust crates that end up in openpacketmon and openpacketmon-capture (normal dependencies only, no dev or build
dependencies), the files bundled under resources/, and the data openpacketmon uses without shipping it.
License texts are taken from the crate sources in the cargo registry and printed once per distinct text.
Adapted from dev/third-party-licenses.py of opennetmon (same author).

Usage (from the repository root, after `cargo fetch`):
    python3 -I dev/third-party-licenses.py           # rewrite the file
    python3 -I dev/third-party-licenses.py --check   # exit 1 if the file is out of date
"""

import json
import pathlib
import re
import subprocess
import sys

TARGET = "x86_64-unknown-linux-gnu"
OUTPUT = pathlib.Path("THIRD-PARTY-LICENSES.txt")
LICENSE_FILE = re.compile(r"^(licen[cs]e|copying|notice|unlicense)([-._].*)?$", re.IGNORECASE)
# the programs whose dependencies are listed
ROOTS = ("openpacketmon", "openpacketmon-capture")

BUNDLED = [
    ("Inter 4.1", "resources/fonts/", "OFL-1.1", "resources/fonts/OFL.txt"),
]
NOTES = """\
Service names (resources/services/services.txt, built into openpacketmon): generated by dev/update-services.py from the
IANA Service Name and Transport Protocol Port Number Registry
(https://www.iana.org/assignments/service-names-port-numbers/). The registry is dedicated to the public domain
(CC0 1.0, https://creativecommons.org/publicdomain/zero/1.0/; https://www.iana.org/help/licensing-terms).

Data used but not shipped
----------------------------------------
Geolocation: openpacketmon contains no geolocation data. Settings -> Geolocation downloads on request the databases
"IP to Country Lite" and "IP to ASN Lite" of DB-IP (https://db-ip.com), licensed under the Creative Commons
Attribution 4.0 International License (CC BY 4.0, https://creativecommons.org/licenses/by/4.0/):
IP Geolocation by DB-IP (https://db-ip.com). openpacketmon shows this attribution while it uses their data.
Other MMDB files (MaxMind GeoLite2 via geoipupdate, IPinfo, ...) are chosen by the user and keep their own terms.

Test data (only in the source repository, not in the packages): resources/test/ipinfo_*_sample.mmdb are sample
databases of IPinfo (https://ipinfo.io, https://github.com/ipinfo/sample-database), unchanged, licensed under
CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/); see resources/test/README.md.

System libraries (installed by the distribution, linked at run time, not shipped): libpcap, ALSA and the libraries of
the display and the graphics card. Their licenses are in /usr/share/doc/<package>/copyright."""


def metadata():
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", TARGET],
        check=True,
        capture_output=True,
        text=True,
    ).stdout
    return json.loads(out)


def shipped_packages(meta):
    """Packages reachable from the programs over normal (runtime) dependency edges, without the workspace itself."""
    packages = {p["id"]: p for p in meta["packages"]}
    nodes = {n["id"]: n for n in meta["resolve"]["nodes"]}
    members = set(meta["workspace_members"])
    roots = [i for i in members if packages[i]["name"] in ROOTS]
    seen, todo = set(roots), list(roots)
    while todo:
        current = todo.pop()
        for dep in nodes[current]["deps"]:
            if any(k["kind"] is None for k in dep["dep_kinds"]) and dep["pkg"] not in seen:
                seen.add(dep["pkg"])
                todo.append(dep["pkg"])
    return sorted((packages[i] for i in seen - members), key=lambda p: (p["name"].lower(), p["version"]))


def license_texts(package):
    folder = pathlib.Path(package["manifest_path"]).parent
    files = sorted(f for f in folder.iterdir() if f.is_file() and LICENSE_FILE.match(f.name))
    return [(f.name, f.read_text(encoding="utf-8", errors="replace").strip()) for f in files]


def add(texts, text, user):
    """Collects users per license text; texts differing only in whitespace count as one."""
    texts.setdefault(" ".join(text.split()), (text, []))[1].append(user)


def render(meta):
    crates = shipped_packages(meta)
    texts = {}  # whitespace-normalized text -> (text, list of "name version (file)")
    missing = []
    lines = [
        "Third-party software in openpacketmon",
        "=====================================",
        "",
        "Generated by dev/third-party-licenses.py from Cargo.lock for " + TARGET + "; do not edit by hand.",
        "openpacketmon itself (including lib/sniffnet-packet-parser) is licensed under the MIT License or the Apache",
        "License 2.0, at your option (LICENSE-MIT, LICENSE-APACHE); it is a fork of Sniffnet, see NOTICE.",
        "",
        f"Rust crates compiled into openpacketmon and openpacketmon-capture ({len(crates)})",
        "-" * 40,
    ]
    for p in crates:
        lines.append(f"{p['name']} {p['version']}: {p.get('license') or 'see license file'}"
                     + (f"  <{p['repository']}>" if p.get("repository") else ""))
        found = license_texts(p)
        if not found:
            missing.append(p)
        for name, text in found:
            add(texts, text, f"{p['name']} {p['version']} ({name})")

    lines += ["", "Bundled files", "-" * 40]
    for label, path, spdx, license_path in BUNDLED:
        lines.append(f"{label} ({path}): {spdx}")
        text = pathlib.Path(license_path).read_text(encoding="utf-8").strip()
        add(texts, text, f"{label} ({license_path})")
    lines.append(NOTES)

    if missing:
        lines += ["", "Crates without a license file in their source; their SPDX license applies:"]
        lines += [f"  {p['name']} {p['version']}: {p.get('license')}" for p in missing]

    lines += ["", "", "License texts", "=" * 40]
    for text, users in texts.values():
        lines += ["", "-" * 72, "Applies to:"]
        lines += [f"  {u}" for u in users]
        lines += ["-" * 72, "", text]
    return "\n".join(lines) + "\n"


def main():
    content = render(metadata())
    if "--check" in sys.argv[1:]:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != content:
            print(f"{OUTPUT} is out of date; run dev/third-party-licenses.py", file=sys.stderr)
            sys.exit(1)
        return
    OUTPUT.write_text(content, encoding="utf-8")
    print(f"wrote {OUTPUT} ({content.count(chr(10))} lines)")


if __name__ == "__main__":
    main()
