#!/usr/bin/env python3
"""Writes resources/services/services.txt from the IANA Service Name and Transport Protocol Port Number Registry.

The registry is dedicated to the public domain (CC0 1.0, joint statement of IANA and IETF of 2021-11-10,
https://www.iana.org/help/licensing-terms). It replaces the nmap list Sniffnet used, which is under the
Nmap Public Source License.

Every TCP or UDP port with a service name gets one line `name<TAB>port/protocol`; port ranges are written as
single ports. Where the registry has several names for a port, the first one is used, except for the few in
PREFERRED. resources/services/categories.txt must have exactly one category per service name (build.rs checks
it): names that are no longer used are removed from it, new names are added as "other" and listed so that a
better category can be chosen by hand.

Usage: dev/update-services.py [service-names-port-numbers.csv]   (without a file the registry is downloaded)
"""

import csv
import datetime
import io
import pathlib
import sys
import urllib.request

URL = "https://www.iana.org/assignments/service-names-port-numbers/service-names-port-numbers.csv"
ROOT = pathlib.Path(__file__).resolve().parent.parent
SERVICES = ROOT / "resources/services/services.txt"
CATEGORIES = ROOT / "resources/services/categories.txt"

CATEGORIES_HEADER = """\
# Modified for openpacketmon (2026), see NOTICE. Based on `resources/services/categories.txt` of Sniffnet
# (https://github.com/GyulyVGC/sniffnet), Copyright (c) 2022 Giuliano Bellini, MIT OR Apache-2.0.
# One category for every service name of services.txt; dev/update-services.py adds new names as "other".

"""

# Ports where a later name of the registry is the one in use today.
PREFERRED = {
    465: "submissions",  # SMTP over TLS (RFC 8314); "urd" is historic
    1701: "l2tp",
    2049: "nfs",
}


def read_registry(path):
    if path:
        return pathlib.Path(path).read_text(encoding="utf-8")
    with urllib.request.urlopen(URL, timeout=60) as response:
        return response.read().decode("utf-8")


def services_of(text):
    """{(port, protocol): name}"""
    names = {}
    for row in csv.DictReader(io.StringIO(text)):
        name = row["Service Name"].strip()
        ports = row["Port Number"].strip()
        protocol = row["Transport Protocol"].strip().lower()
        if not name or not ports or protocol not in ("tcp", "udp"):
            continue
        first, _, last = ports.partition("-")
        for port in range(int(first), int(last or first) + 1):
            preferred = PREFERRED.get(port)
            if (port, protocol) not in names or name == preferred:
                names[(port, protocol)] = name
    return names


def main():
    names = services_of(read_registry(sys.argv[1] if len(sys.argv) > 1 else None))
    today = datetime.date.today().isoformat()
    lines = [
        "# Generated by dev/update-services.py from the IANA Service Name and Transport Protocol Port Number Registry",
        f"# ({URL}, retrieved {today}).",
        "# The registry is dedicated to the public domain (CC0 1.0, https://www.iana.org/help/licensing-terms).",
        "# Don't edit this file manually.",
        "",
    ]
    lines += [f"{name}\t{port}/{protocol}" for (port, protocol), name in sorted(names.items())]
    SERVICES.write_text("\n".join(lines) + "\n", encoding="utf-8")

    used = set(names.values())
    categories = {}
    for line in CATEGORIES.read_text(encoding="utf-8").splitlines():
        if line.strip() and not line.startswith("#"):
            name, category = line.split("\t")
            categories[name] = category
    added = sorted(used - categories.keys())
    removed = len(categories.keys() - used)
    categories = {name: categories.get(name, "other") for name in used}
    CATEGORIES.write_text(
        CATEGORIES_HEADER + "".join(f"{name}\t{categories[name]}\n" for name in sorted(categories)), encoding="utf-8"
    )

    print(f"{len(names)} ports, {len(used)} service names; categories: {removed} removed, {len(added)} added as other")
    if added:
        print("New names (category other, check them):", " ".join(added))


if __name__ == "__main__":
    main()
